// Local Git-release adapter. Unlike legacy js-overlay, never rewrites package.json or index flags.
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { readMap, family } = require('./pnpm-overlay-hook.cjs');
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trimEnd();
const read = name => existsSync(join(root, name)) ? readFileSync(join(root, name), 'utf8') : null;
const stateDir = resolve(root, git('rev-parse', '--git-path', 'pnpm-local-overlay'));
const stateFile = join(stateDir, 'state.json');
const hook = '.pnpmfile.cjs';
const map = 'pnpm.local.json';
const generated = "// Generated by scripts/pnpm-overlay; local-only, like composer.local.json.\nmodule.exports = require('./scripts/pnpm-overlay-hook.cjs')(__dirname);\n";
const canonical = ['package.json', 'pnpm-lock.yaml'];
const inputs = ['package.json', '.npmrc', 'pnpm-workspace.yaml', map, 'scripts/pnpm-overlay-hook.cjs'];
const save = state => writeFileSync(stateFile, JSON.stringify(state, null, 2) + '\n');
const assert = (condition, message) => { if (!condition) throw Error(message); };
const pnpm = args => {
    const bin = process.env.PNPM_OVERLAY_PNPM || 'pnpm';
    const p = spawnSync(bin, args, { cwd: root, stdio: 'inherit' });
    return p.status === 0;
};
function cleanIndex(base) {
    const flags = git('ls-files', '-v', '--', ...canonical).split('\n');
    assert(flags.length === 2 && flags.every(line => line.startsWith('H ')), 'canonical inputs have hidden or missing index entries');
    for (const file of canonical) {
        const head = execFileSync('git', ['show', `HEAD:${file}`], { cwd: root, encoding: 'utf8' });
        const index = execFileSync('git', ['show', `:${file}`], { cwd: root, encoding: 'utf8' });
        assert(head === base[file] && index === base[file], `${file}: committed/index baseline changed; refuse restoration`);
    }
}
function guard(state) {
    cleanIndex(state.base);
    for (const file of inputs) assert(read(file) === state.inputs[file], `${file}: drift; nothing restored`);
    assert(read(hook) === (state.phase === 'disabling' ? null : generated), `${hook}: drift; nothing restored`);
    assert(read('pnpm-lock.yaml') === state.lock, 'pnpm-lock.yaml: drift; nothing restored');
}
function ensureIgnored(file) {
    assert(!git('ls-files', '--', file), `${file} must not be tracked`);
    assert(spawnSync('git', ['check-ignore', '-q', '--', file], { cwd: root }).status === 0, `${file} must be gitignored`);
}
function on() {
    assert(!existsSync(resolve(root, git('rev-parse', '--git-path', 'js-overlay'), 'package.json')), 'legacy js-overlay is active; turn it off first');
    if (existsSync(stateFile)) {
        const state = JSON.parse(readFileSync(stateFile)); guard(state);
        assert(state.phase === 'active', 'previous install incomplete; run scripts/pnpm-overlay off first');
        console.log('pnpm-overlay: already on; guarded inputs unchanged'); return;
    }
    assert(!existsSync(stateDir), 'incomplete state directory; inspect before recovery');
    ensureIgnored(hook); ensureIgnored(map);
    assert(read(hook) === null, 'existing pnpmfile hook will not be overwritten');
    const base = Object.fromEntries(canonical.map(file => [file, read(file)])); cleanIndex(base);
    const manifest = JSON.parse(base['package.json']);
    assert(manifest.packageManager === 'pnpm@9.15.3', 'adapter requires packageManager pnpm@9.15.3');
    const version = spawnSync(process.env.PNPM_OVERLAY_PNPM || 'pnpm', ['--version'], { cwd: root, encoding: 'utf8' });
    assert(version.status === 0 && version.stdout.trim() === '9.15.3', 'adapter requires pnpm 9.15.3');
    assert(!/(?:pnpmfileChecksum:|(?:^|[\s'":])(?:link:|file:|workspace:))/.test(base['pnpm-lock.yaml']), 'canonical lock already contains local overlay state');
    assert(!Object.keys(manifest.pnpm?.overrides || {}).some(key => /@(splicewire|schemastud)\//.test(key)), 'first-party pnpm.overrides defeat readPackage; migrate them explicitly before enabling');
    const entries = readMap(root);
    for (const [name, entry] of Object.entries(entries)) {
        assert(family(name), `${name}: unsupported package scope`);
        const specs = ['dependencies', 'devDependencies', 'optionalDependencies'].flatMap(s => manifest[s]?.[name] === undefined ? [] : [manifest[s][name]]);
        assert(specs.length && specs.every(spec => spec === entry.release), `${name}: root must directly declare the configured exact release (no registry input migration)`);
    }
    const state = { phase: 'installing', base, inputs: Object.fromEntries(inputs.map(file => [file, read(file)])), lock: base['pnpm-lock.yaml'] };
    mkdirSync(stateDir); save(state); writeFileSync(join(root, hook), generated, { flag: 'wx' });
    const ok = pnpm(['install', '--no-frozen-lockfile']);
    state.lock = read('pnpm-lock.yaml'); state.phase = ok ? 'active' : 'failed'; save(state);
    // A failed install keeps its precise resulting lock, so off can restore without guessing or hiding dirt.
    guard(state); assert(ok, 'overlay install failed; guarded state retained; run scripts/pnpm-overlay off');
    console.log('pnpm-overlay: on; manifest unchanged, local lock remains visible to git');
}
function off() {
    if (!existsSync(stateFile)) { assert(read(hook) === null, 'unowned pnpmfile hook exists; not removing it'); console.log('pnpm-overlay: already off'); return; }
    const state = JSON.parse(readFileSync(stateFile)); guard(state);
    writeFileSync(join(root, 'pnpm-lock.yaml'), state.base['pnpm-lock.yaml']);
    rmSync(join(root, hook), { force: true });
    state.phase = 'disabling'; state.lock = state.base['pnpm-lock.yaml']; save(state);
    assert(pnpm(['install', '--frozen-lockfile', '--ignore-pnpmfile']), 'canonical install failed; restored lock retained; retry off');
    guard(state); rmSync(stateDir, { recursive: true });
    console.log('pnpm-overlay: off; canonical lock restored byte-for-byte and frozen install passed');
}
function status() {
    if (!existsSync(stateFile)) { console.log('pnpm-overlay: off'); return; }
    const state = JSON.parse(readFileSync(stateFile)); guard(state); console.log(`pnpm-overlay: ${state.phase}`);
}
try {
    const command = { on, off, status }[process.argv[2]];
    assert(command && process.argv.length === 3, 'usage: scripts/pnpm-overlay on|off|status'); command();
} catch (error) { console.error(`pnpm-overlay: ${error.message}`); process.exitCode = 1; }
